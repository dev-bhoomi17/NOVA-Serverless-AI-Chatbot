/* =====================================================
   03. BUILD GEMINI CONVERSATION CONTENT
===================================================== */

function buildContents(history, latestMessage) {

    const previousMessages = history.map((item) => ({

        role: item.role === "assistant" ? "model" : "user",

        parts: [
            { text: item.content }
        ]

    }));

    return [

        ...previousMessages,

        {
            role: "user",
            parts: [
                { text: latestMessage }
            ]
        }

    ];

}


/* =====================================================
   04. CALL GEMINI
===================================================== */

async function callGemini({
    message,
    history,
    signal,
    configuration
}) {

    const { apiKey, model } = configuration;

    const endpoint =
        `${GEMINI_API_BASE}/${encodeURIComponent(model)}:generateContent`;

    const response = await fetch(endpoint, {

        method: "POST",

        headers: {

            "Content-Type": "application/json",

            "x-goog-api-key": apiKey

        },

        body: JSON.stringify({

            systemInstruction: {

                parts: [
                    { text: SYSTEM_INSTRUCTION }
                ]

            },

            contents: buildContents(history, message),

            generationConfig: {

                temperature: 0.7,

                maxOutputTokens: 900

            }

        }),

        signal

    });


    const data = await response.json().catch(() => null);


    if (!response.ok) {

        const error = new Error(
            response.status === 429
                ? "The AI service is temporarily rate-limited. Please try again later."
                : response.status === 401 ||
                  response.status === 403
                    ? "The AI service rejected its server credentials. Check the server configuration."
                    : "The AI service could not process this request."
        );

        error.status =
            response.status === 429 ? 503 : 502;

        throw error;

    }


    const reply = data?.candidates?.[0]?.content?.parts

        ?.map((part) => part.text || "")

        .join("")
        .trim();


    if (!reply) {

        const error = new Error(
            "The AI service returned no usable text response."
        );

        error.status = 502;

        throw error;

    }

    return reply;

}


/* =====================================================
   05. PUBLIC RESPONSE FUNCTION
===================================================== */

export async function generateAssistantReply({
    message,
    history = [],
    signal
}) {

    const configuration = getGeminiConfiguration();


    // Local demo mode: no external provider request
    if (!configuration) {

        return {

            reply: generateDemoReply(message),

            mode: "demo"

        };

    }


    // Real model request: key is only read on the server
    const reply = await callGemini({

        message,

        history,

        signal,

        configuration

    });


    return {

        reply,

        mode: "live"

    };

}
