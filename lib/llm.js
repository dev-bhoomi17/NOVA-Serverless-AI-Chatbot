/* =====================================================
   01. PROVIDER CONFIGURATION
===================================================== */

const GEMINI_API_BASE =
    "https://generativelanguage.googleapis.com/v1beta/models";


function getGeminiConfiguration() {

    const apiKey = process.env.GEMINI_API_KEY?.trim();

    const model =
        process.env.GEMINI_MODEL?.trim() || "gemini-3.8-flash";

    // Treat the template placeholder as an absent key.
    if (!apiKey || apiKey === "your_api_key_here") {
        return null;
    }

    // Prevent malformed model names entering the URL.
    if (!/^[a-zA-Z0-9._-]+$/.test(model)) {

        throw new Error("Invalid server-side model configuration.");

    }

    return { apiKey, model };

}


